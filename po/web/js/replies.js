export function templateReply({ label } = {}) {
  const name = label || '这个宝贝';
  if (label && KB[label]) return { text: KB[label], source: 'template' };
  if (label && /色的/.test(label)) {
    return { text: `${label}呀！它是画面里最亮眼的颜色，你的小眼睛真会找！想用这个颜色画一幅画吗？`, source: 'template' };
  }
  return {
    text: `这是${name}呀！王冠也觉得它很有意思。你想知道它的什么小秘密呢？我们可以再仔细看看它！`,
    source: 'template',
  };
}
